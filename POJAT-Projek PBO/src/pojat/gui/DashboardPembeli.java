    private void tampilkanInfoPembeli() {
        if (user != null) {
            String hp = (user.getNoHp() == null || user.getNoHp().isEmpty()) ? "-" : user.getNoHp();
            lblSubtitle.setText("Selamat datang, " + user.getNamaLengkap() + "  |  No. HP: " + hp);
            lblUserSidebar.setText(user.getNamaLengkap());
        }
        int itemCount = pojat.util.KeranjangPOJAT.getItems().size();
        btnKeranjang.setText("Keranjang Belanja (" + itemCount + " item)");
    }

    private void editProfil() {
        if (user == null) {
            return;
        }
        JTextField txtNama = new JTextField(user.getNamaLengkap());
        JTextField txtNoHp = new JTextField(user.getNoHp() == null ? "" : user.getNoHp());
        JPasswordField txtPassBaru = new JPasswordField();

        JPanel panel = new JPanel(new GridLayout(3, 2, 8, 8));
        panel.add(new JLabel("Nama Lengkap:"));
        panel.add(txtNama);
        panel.add(new JLabel("No. HP (WhatsApp/Kontak):"));
        panel.add(txtNoHp);
        panel.add(new JLabel("Password Baru (opsional):"));
        panel.add(txtPassBaru);

        int hasil = JOptionPane.showConfirmDialog(
            this,
            panel,
            "Profil Pembeli (@" + user.getUsername() + ")",
            JOptionPane.OK_CANCEL_OPTION,
            JOptionPane.PLAIN_MESSAGE
        );
        if (hasil != JOptionPane.OK_OPTION) {
            return;
        }

        String namaBaru = txtNama.getText().trim();
        String hpBaru = txtNoHp.getText().trim();
        char[] passChars = txtPassBaru.getPassword();
        String passBaru = new String(passChars);
        Arrays.fill(passChars, '\0');

        if (namaBaru.isEmpty() || hpBaru.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Nama Lengkap dan No. HP wajib diisi!");
            return;
        }
        if (!passBaru.isEmpty() && passBaru.length() < 6) {
            JOptionPane.showMessageDialog(this, "Password baru minimal 6 karakter!");
            return;
        }

        boolean updatePass = !passBaru.isEmpty();
        String hashBaru = updatePass ? PasswordUtil.hashPassword(passBaru) : user.getPasswordHash();
        User updated = new User(user.getIdUser(), user.getUsername(), hashBaru, namaBaru, hpBaru, user.getRole());

        try {
            if (new UserDAO().updateUser(updated, updatePass)) {
                this.user = updated;
                tampilkanInfoPembeli();
                JOptionPane.showMessageDialog(this, "Profil berhasil diperbarui!");
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Gagal memperbarui profil: " + e.getMessage());
        }
    }

