    private void tampilkanInfoAdmin() {
        if (user != null) {
            lblSubtitle.setText("Selamat datang, " + user.getNamaLengkap()
                    + "  |  Username: " + user.getUsername()
                    + "  |  Role: " + user.getRole());
            lblUserSidebar.setText(user.getNamaLengkap());
        }
    }

