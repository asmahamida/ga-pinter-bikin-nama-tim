    private void prosesDaftar() {
        String username = txtUsername.getText().trim();
        String namaLengkap = txtNamaLengkap.getText().trim();
        String noHp = txtNoHp.getText().trim();
        String role = String.valueOf(cmbRole.getSelectedItem());

        char[] passChars = txtPassword.getPassword();
        char[] confChars = txtKonfirmasi.getPassword();
        String password = new String(passChars);
        String konfirmasi = new String(confChars);
        Arrays.fill(passChars, '\0');
        Arrays.fill(confChars, '\0');

        if (username.isEmpty() || namaLengkap.isEmpty() || noHp.isEmpty()
                || password.isEmpty() || konfirmasi.isEmpty()) {
            JOptionPane.showMessageDialog(
                this,
                "Semua field wajib diisi!",
                "Peringatan",
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        if (username.length() > 50 || namaLengkap.length() > 100 || noHp.length() > 20) {
            JOptionPane.showMessageDialog(
                this,
                "Panjang melebihi batas (Username max 50, Nama max 100, No HP max 20)!",
                "Peringatan",
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        if (password.length() < 6) {
            JOptionPane.showMessageDialog(
                this,
                "Password minimal 6 karakter!",
                "Peringatan",
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        if (!password.equals(konfirmasi)) {
            JOptionPane.showMessageDialog(
                this,
                "Password dan konfirmasi password tidak sama!",
                "Peringatan",
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        try {
            if (userDAO.usernameExists(username)) {
                JOptionPane.showMessageDialog(
                    this,
                    "Username sudah digunakan, silakan pilih username lain!",
                    "Registrasi Gagal",
                    JOptionPane.WARNING_MESSAGE
                );
                return;
            }

            String hash = PasswordUtil.hashPassword(password);
            User userBaru = new User(0, username, hash, namaLengkap, noHp, role);

            if (userDAO.tambahUser(userBaru)) {
                String pesan = "UMKM".equalsIgnoreCase(role)
                        ? "Registrasi akun UMKM berhasil!\nSilakan login lalu lengkapi Profil Toko Anda di Dashboard UMKM."
                        : "Registrasi berhasil! Silakan login menggunakan akun Anda.";
                JOptionPane.showMessageDialog(
                    this,
                    pesan
                );
                new LoginFrame().setVisible(true);
                dispose();
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(
                this,
                "Gagal mendaftarkan akun: " + e.getMessage(),
                "Kesalahan Database",
                JOptionPane.ERROR_MESSAGE
            );
        }
    }

