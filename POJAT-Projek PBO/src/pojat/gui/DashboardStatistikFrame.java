    private void tampilkanStatistik(boolean showErrorDialog) {
        try {
            lblUMKM.setText(String.valueOf(statistikDAO.getTotalUMKM()));
            lblMenu.setText(String.valueOf(statistikDAO.getTotalMenu()));
            lblPesanan.setText(String.valueOf(statistikDAO.getTotalPesanan()));
            lblBatch.setText(String.valueOf(statistikDAO.getTotalBatch()));
            lblOmzet.setText(UIHelper.formatRupiah(statistikDAO.getTotalOmzet()));

            StringBuilder sb = new StringBuilder();
            sb.append("PESANAN PER STATUS:\n");
            List<Object[]> perStatus = statistikDAO.getStatistikPerStatus();
            if (perStatus.isEmpty()) {
                sb.append("  - Belum ada transaksi pesanan.\n");
            } else {
                for (Object[] r : perStatus) {
                    sb.append("  - ").append(r[0])
                      .append(": ").append(r[1]).append(" pesanan (")
                      .append(UIHelper.formatRupiah(((Number) r[2]).doubleValue())).append(")\n");
                }
            }
            sb.append("\nPERFORMA PER UMKM (Omzet Non-Dibatalkan):\n");
            List<Object[]> perUmkm = statistikDAO.getStatistikPerUMKM();
            if (perUmkm.isEmpty()) {
                sb.append("  - Belum ada UMKM terdaftar.\n");
            } else {
                for (Object[] u : perUmkm) {
                    sb.append("  - ").append(u[0])
                      .append(": ").append(u[1]).append(" pesanan | Omzet ")
                      .append(UIHelper.formatRupiah(((Number) u[2]).doubleValue())).append("\n");
                }
            }
            txtRincianArea.setText(sb.toString());
            txtRincianArea.setCaretPosition(0);
        } catch (SQLException e) {
            if (showErrorDialog) {
                JOptionPane.showMessageDialog(
                    this,
                    "Gagal memuat statistik: " + e.getMessage()
                );
            } else {
                txtRincianArea.setText("Database belum terhubung. Klik Refresh Statistik setelah MySQL aktif.");
            }
        }
    }

